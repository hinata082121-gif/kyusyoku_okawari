export const menuIds = Object.keys(lunchMenus) as LunchMenuId[];
export const lunchMenuList = menuIds.map((id) => lunchMenus[id]);

export function selectRandomLunchMenuByWeight(menus: LunchMenu[]): LunchMenu {
  const totalWeight = menus.reduce((total, item) => total + Math.max(0, item.appearanceWeight), 0);
  if (totalWeight <= 0) return Phaser.Math.RND.pick(menus);

  let roll = Phaser.Math.Between(1, totalWeight);
  for (const item of menus) {
    roll -= Math.max(0, item.appearanceWeight);
    if (roll <= 0) return item;
  }
  return menus[menus.length - 1];
}

export function getRandomMenu(): LunchMenu {
  return selectRandomLunchMenuByWeight(lunchMenuList);
}
